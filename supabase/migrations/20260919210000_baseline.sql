create or replace function public.comprobar_limite_citas_dia()
returns trigger
language plpgsql
as $function$
declare
  total_citas integer;
begin

  -- El límite de 6 solo se aplica a SpeedBikes (taller_id = 1)
  if new.taller_id = 1
     and new.estado in ('Pendiente', 'Confirmada') then

    select count(*)
    into total_citas
    from public.reservas
    where taller_id = new.taller_id
      and dia = new.dia
      and estado in ('Pendiente', 'Confirmada')
      and id <> coalesce(new.id, 0);

    if total_citas >= 6 then
      raise exception 'SpeedBikes ya tiene el máximo de 6 citas para este día';
    end if;

  end if;

  return new;
end;
$function$;

create trigger comprobar_limite_citas_dia
  before insert or update on public.reservas
  for each row execute function public.comprobar_limite_citas_dia();

