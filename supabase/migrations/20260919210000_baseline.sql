-- reservas
create policy "Permitir lectura reservas" on public.reservas
  for select to anon using (true);
create policy "cliente puede solicitar reserva" on public.reservas
  for insert to anon with check (estado = 'Pendiente'::text);
create policy "usuarios autenticados pueden ver reservas de su taller" on public.reservas
  for select to authenticated
  using (taller_id in (select talleres.id from public.talleres where talleres.user_id = auth.uid()));
create policy "taller puede crear reservas de su propio taller" on public.reservas
  for insert to authenticated
  with check (
    (exists (select 1 from public.talleres t where t.id = reservas.taller_id and t.user_id = auth.uid()))
    and (estado = any (array['Pendiente'::text, 'Confirmada'::text]))
  );
create policy "taller puede confirmar o cancelar sus reservas" on public.reservas
  for update to authenticated
  using (exists (select 1 from public.talleres t where t.id = reservas.taller_id and t.user_id = auth.uid()))
  with check (
    (exists (select 1 from public.talleres t where t.id = reservas.taller_id and t.user_id = auth.uid()))
    and (estado = any (array['Confirmada'::text, 'Cancelada'::text]))
  );

