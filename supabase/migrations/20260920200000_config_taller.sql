-- ----------------------------------------------------------------------------
-- 8. Ocupación pública acotada a lo que consulta el formulario (hoy y 90 días)
-- ----------------------------------------------------------------------------
create or replace function public.ocupacion_dia(p_taller_id bigint, p_dia date)
returns table (hora time without time zone, total integer)
language sql
stable
security definer
set search_path = ''
as $$
  select r.hora, count(*)::integer
  from public.reservas r
  join public.talleres t on t.id = r.taller_id and t.activo
  where r.taller_id = p_taller_id
    and r.dia = p_dia
    and p_dia between (now() at time zone 'Europe/Madrid')::date and (now() at time zone 'Europe/Madrid')::date + 90
    and r.estado in ('Pendiente', 'Confirmada')
  group by r.hora
  order by r.hora;
$$;
